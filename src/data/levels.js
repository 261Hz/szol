/**
 * Look up the proficiency level for a word in a given language.
 * Returns { label, tip, cls } or null if no data is available.
 *
 * @param {string} word - the vocab word as stored
 * @param {string} lang - ISO 639-1 language code
 */
export function getWordLevel(word, lang) {
  if (!word || !lang) return null
  const w = word.toLowerCase().trim()

  if (lang === 'zh') {
    const lvl = HSK[word] ?? HSK[w]
    if (!lvl) return null
    return { label: `HSK ${lvl}`, ...HSK_CONFIG[lvl] }
  }

  if (lang === 'ja') {
    const lvl = JLPT[word] ?? JLPT[w]
    if (!lvl) return null
    return { label: lvl, ...JLPT_CONFIG[lvl] }
  }

  if (lang === 'ko') {
    const lvl = TOPIK[word] ?? TOPIK[w]
    if (!lvl) return null
    const label = lvl <= 2 ? 'TOPIK I' : lvl <= 4 ? 'TOPIK II' : 'TOPIK III'
    return { label, ...TOPIK_CONFIG[lvl] }
  }

  // CEFR for en, es, fr, de, it, ru, ar, he, el, hu, nl, pt …
  // English has the fullest coverage; other languages return null when not found.
  const lvl = EN_CEFR[w]
  if (!lvl) return null
  return { label: lvl, ...CEFR_CONFIG[lvl] }
}
