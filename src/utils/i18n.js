// t() = "translate". The main function used throughout the app to get translated text.
// lang = a language code like 'es', 'el', 'zh'
// key  = a UI key like 'read', 'save', 'noStory'
export function t(lang, key) {
  // UI[lang]?.[key] = try to get the translation for this language and key.
  //   ?. = optional chaining: if UI[lang] doesn't exist, return undefined (not crash).
  // || UI['es'][key] = if not found, fall back to the Spanish translation.
  //   (Spanish is the fallback language -- most complete during development.)
  // || key = if even Spanish doesn't have it, just return the raw key name as a last resort.
  //   (This makes missing translations visible in the UI rather than showing nothing.)
  return UI[lang]?.[key] || UI['es'][key] || key
}
